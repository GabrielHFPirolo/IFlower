-- =====================================================================
-- IFlower - DDL (PostgreSQL 16)
-- Deve permanecer em sincronia com as entidades JPA (ddl-auto=validate).
-- Convenção: tipos monetários em NUMERIC(12,2); enums como VARCHAR + CHECK.
-- =====================================================================

-- ---------- Usuário (herança JOINED: usuario + cliente | vendedor) ----------
CREATE TABLE usuario (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(120) NOT NULL,
    email       VARCHAR(160) NOT NULL UNIQUE,
    senha_hash  VARCHAR(255) NOT NULL,
    telefone    VARCHAR(20),
    cep         VARCHAR(8),
    logradouro  VARCHAR(160),
    numero      VARCHAR(20),
    bairro      VARCHAR(80),
    cidade      VARCHAR(80),
    uf          VARCHAR(2),
    ativo       BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE cliente (
    id   BIGINT PRIMARY KEY REFERENCES usuario (id) ON DELETE CASCADE,
    cpf  VARCHAR(11) NOT NULL UNIQUE
);

CREATE TABLE vendedor (
    id  BIGINT PRIMARY KEY REFERENCES usuario (id) ON DELETE CASCADE
);

-- ---------- Loja e produtos ----------
CREATE TABLE loja (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vendedor_id BIGINT NOT NULL UNIQUE REFERENCES vendedor (id),
    nome        VARCHAR(120) NOT NULL,
    descricao   VARCHAR(500),
    cnpj        VARCHAR(14) NOT NULL UNIQUE,
    cep         VARCHAR(8),
    logradouro  VARCHAR(160),
    numero      VARCHAR(20),
    bairro      VARCHAR(80),
    cidade      VARCHAR(80),
    uf          VARCHAR(2),
    abertura    TIME,
    fechamento  TIME,
    ativa       BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE produto (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loja_id                BIGINT NOT NULL REFERENCES loja (id),
    nome                   VARCHAR(120) NOT NULL,
    foto                   VARCHAR(500),
    descricao              VARCHAR(1000),
    preco                  NUMERIC(12,2) NOT NULL CHECK (preco > 0),
    permite_personalizacao BOOLEAN NOT NULL DEFAULT FALSE,
    ativo                  BOOLEAN NOT NULL DEFAULT TRUE
);

-- ---------- Carrinho ----------
CREATE TABLE carrinho (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL UNIQUE REFERENCES cliente (id),
    loja_id    BIGINT REFERENCES loja (id)
);

CREATE TABLE item_carrinho (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carrinho_id    BIGINT NOT NULL REFERENCES carrinho (id) ON DELETE CASCADE,
    produto_id     BIGINT NOT NULL REFERENCES produto (id),
    quantidade     INTEGER NOT NULL CHECK (quantidade > 0),
    personalizacao VARCHAR(300)
);

-- ---------- Pedido ----------
CREATE TABLE pedido (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id  BIGINT NOT NULL REFERENCES cliente (id),
    loja_id     BIGINT NOT NULL REFERENCES loja (id),
    data_pedido TIMESTAMP NOT NULL,
    status      VARCHAR(30) NOT NULL CHECK (status IN (
                    'AGUARDANDO_PAGAMENTO', 'CONFIRMADO', 'EM_PREPARO', 'SAIU_PARA_ENTREGA',
                    'PRONTO_PARA_RETIRADA', 'ENTREGUE', 'CANCELADO')),
    valor_total NUMERIC(12,2) NOT NULL CHECK (valor_total >= 0)
);

CREATE TABLE item_pedido (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id      BIGINT NOT NULL REFERENCES pedido (id) ON DELETE CASCADE,
    produto_id     BIGINT NOT NULL REFERENCES produto (id),
    quantidade     INTEGER NOT NULL CHECK (quantidade > 0),
    preco_unitario NUMERIC(12,2) NOT NULL CHECK (preco_unitario > 0),
    personalizacao VARCHAR(300)
);

CREATE TABLE entrega (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id     BIGINT NOT NULL UNIQUE REFERENCES pedido (id) ON DELETE CASCADE,
    data_entrega  DATE NOT NULL,
    horario       TIME NOT NULL,
    tipo_retirada VARCHAR(20) NOT NULL CHECK (tipo_retirada IN ('ENTREGA', 'RETIRADA_NA_LOJA')),
    cep           VARCHAR(8),
    logradouro    VARCHAR(160),
    numero        VARCHAR(20),
    bairro        VARCHAR(80),
    cidade        VARCHAR(80),
    uf            VARCHAR(2),
    selecionada   BOOLEAN NOT NULL,
    cancelada     BOOLEAN NOT NULL
);

-- ---------- Pagamento (herança SINGLE_TABLE; "tipo" é a coluna discriminadora) ----------
CREATE TABLE pagamento (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id      BIGINT NOT NULL REFERENCES pedido (id) ON DELETE CASCADE,
    tipo           VARCHAR(10) NOT NULL CHECK (tipo IN ('PIX', 'CARTAO', 'BOLETO')),
    valor          NUMERIC(12,2) NOT NULL CHECK (valor >= 0),
    status         VARCHAR(10) NOT NULL CHECK (status IN ('PENDENTE', 'APROVADO', 'RECUSADO')),
    data_pagamento TIMESTAMP,
    chave_pix      VARCHAR(140),
    ultimos_digitos VARCHAR(4),
    codigo_barras  VARCHAR(48)
);

-- ---------- Avaliação ----------
CREATE TABLE avaliacao (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id     BIGINT NOT NULL REFERENCES cliente (id),
    loja_id        BIGINT NOT NULL REFERENCES loja (id),
    nota           INTEGER NOT NULL CHECK (nota BETWEEN 1 AND 5),
    comentario     VARCHAR(500),
    data_avaliacao TIMESTAMP NOT NULL,
    CONSTRAINT uk_avaliacao_cliente_loja UNIQUE (cliente_id, loja_id)
);

-- ---------- Índices de apoio às consultas mais frequentes ----------
CREATE INDEX idx_loja_cidade_uf     ON loja (LOWER(cidade), UPPER(uf));
CREATE INDEX idx_produto_loja       ON produto (loja_id) WHERE ativo;
CREATE INDEX idx_pedido_cliente     ON pedido (cliente_id, data_pedido DESC);
CREATE INDEX idx_pedido_loja        ON pedido (loja_id, data_pedido DESC);
CREATE INDEX idx_item_pedido_pedido ON item_pedido (pedido_id);
CREATE INDEX idx_pagamento_pedido   ON pagamento (pedido_id);
CREATE INDEX idx_avaliacao_loja     ON avaliacao (loja_id);
